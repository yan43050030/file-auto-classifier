def apply_tooltips(win):
    for btn in win.findChildren(QAbstractButton):
        if btn.toolTip():
            continue
        text = (btn.text() or '').strip()
        for key in sorted(TIPS, key=len, reverse=True):
            if text.startswith(key):
                btn.setToolTip(TIPS[key])
                break
    for attr, tip in WIDGET_TIPS.items():
        w = getattr(win, attr, None)
        if w is not None and not w.toolTip():
            w.setToolTip(tip)
