def is_org(name: str) -> bool:
    n = (name or "").strip()
    return bool(n) and any(w in n for w in _ORG_WORDS)


def is_person_name(name: str) -> bool:
    """看起来像个人姓名：2~4 个汉字（或少数民族带间隔号），且不含单位用词。"""
    n = re.sub(r"\s", "", name or "")
    if not _PERSON_RE.match(n) or is_org(n):
        return False
    if "·" in n or "•" in n:
        return True
    return n[:2] in _SURNAMES_2 or n[0] in _SURNAMES_1
